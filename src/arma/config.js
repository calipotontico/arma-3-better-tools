import {doorGroups,validateDoorMotion} from '../door-motion.js';
import {sideCondition} from '../interaction.js';
import {markerScript} from './interaction-config.js';
import {seatingConfig} from './seating-config.js';
import { multiLightConfig } from './light-config.js';
import { glassConfig } from './glass-config.js';
export function validateOptions(o){
  if(!/^[a-z][a-z0-9_]{2,39}$/.test(o.id))throw new Error('El identificador debe tener 3–40 letras minúsculas, números o guiones bajos, y empezar por una letra.');
  if(!Number.isFinite(o.scale)||o.scale<=0||o.scale>1000)throw new Error('Escala de exportación no válida.');
  return {...o,label:String(o.label||o.id).slice(0,100),author:String(o.author||'').slice(0,100)};
}
const q=s=>'"'+String(s).replaceAll('"','""').replace(/[\r\n\x00]/g,' ')+'"';
export const generatedHeader='//// Generado con Arma 3 Better Tools\n//// Discord: https://discord.gg/g5WJfUxcRj\n\n';
export function doorActionText(door,opening){
  const custom=opening?door.actionOpen:door.actionClose;
  return typeof custom==='string'&&custom.trim()?custom.trim().slice(0,100):(opening?'Abrir ':'Cerrar ')+(door.label||'puerta');
}
export function configs(options,doors,light=null,panes=[],ladders=[],seats=[]){
  doors.forEach(validateDoorMotion);const o=validateOptions(options),id=o.id,model=id+'_building',skeleton=id+'_skeleton';
  const lights=Array.isArray(light)?light:light?[light]:[],lighting=multiLightConfig(id,lights);
  const glass=glassConfig(id,panes,lights.length),sections=[...lighting.sections,...glass.sections],bones=[...doors.flatMap((_,i)=>[`"door_${i+1}"`,'""']),...glass.bones];
  const marker=markerScript(doors,lights);
  const seating=seatingConfig(id,seats);
  const init=[...(marker?['interaction']:[]),...(lights.length?['light']:[]),...(panes.length?['glass']:[])].map(name=>`_this execVM '\\${id}\\scripts\\${name}.sqf';`).join(' ')+(seating.init||'');
  const sources=doors.map((d,i)=>`class Door_${i+1}_source { source="user"; animPeriod=1; initPhase=0; };`).join('\n');
  const actions=doorGroups(doors).map(({door:d,index:i,members})=>{const n=i+1;if(d.interactionMode==='marker')return '';const permission=sideCondition(d);const opened=members.map(j=>`(this animationSourcePhase 'Door_${j+1}_source' >= 0.5)`).join(' || ');const statement=value=>members.map(j=>`this animateSource ['Door_${j+1}_source',${value}];`).join(' ');return `class Open_${n} { displayName=${q(doorActionText(d,true))}; position="door_${n}_trigger"; radius=3; onlyForPlayer=1; condition="(${permission}) && {!(${opened})}"; statement="${statement(1)}"; };
class Close_${n}: Open_${n} { displayName=${q(doorActionText(d,false))}; condition="(${permission}) && {${opened}}"; statement="${statement(0)}"; };`;}).join('\n');
  return {model,assets:[...lighting.assets,...glass.assets,...(marker?[marker]:[]),...seating.assets].map(asset=>asset.name.endsWith('.sqf')?{...asset,text:generatedHeader+asset.text}:asset),
    config:`// Generated by Arma 3 Better Tools by Calipo\nclass CfgPatches { class ${id} { units[]={"Land_${model}"}; weapons[]={}; requiredVersion=${(marker||seats.length)?'2.22':'2.0'}; requiredAddons[]={"A3_Structures_F"${seats.length?', "A3_Anims_F_Config_Sdr"':''}}; author=${q(o.author)}; }; };
class CfgEditorCategories { class ${id}_category { displayName="Arma 3 Better Tools"; }; };
${seating.functions}
class CfgEditorSubcategories { class ${id}_buildings { displayName="Edificios"; }; };
class CfgVehicles { class House_F; class Land_${model}: House_F { scope=2; scopeCurator=2; displayName=${q(o.label)}; author=${q(o.author)}; model="\\${id}\\${model}.p3d"; editorCategory="${id}_category"; editorSubcategory="${id}_buildings"; vehicleClass="Structures"; armor=10000; destrType="${panes.length?'DestructBuilding':'DestructNo'}"; numberOfDoors=${doors.length};
${ladders.length?`ladders[]={${ladders.map(l=>`{"${l.name}_start","${l.name}_end",${l.radius??2.5}}`).join(',')}};`:''}
${seating.property}
${panes.length?'armorStructural=1000; class DestructionEffects {};':''}
class AnimationSources { ${sources} ${glass.sources} };
${sections.length?`hiddenSelections[]={${sections.join(',')}};`:''}
${init?`class EventHandlers { init="${init}"; };`:''}
${glass.hitpoints}
class UserActions { ${actions} ${lighting.actions} };
}; };\n`,
    modelCfg:`class CfgSkeletons { class ${skeleton} { isDiscrete=1; skeletonInherit=""; skeletonBones[]={${bones.join(',')}}; }; };
class CfgModels { class ${model} { sectionsInherit=""; sections[]={${sections.join(',')}}; skeletonName="${skeleton}"; class Animations {
${glass.animations}
${doors.map((d,i)=>`class Door_${i+1}_rot { type="${d.motion==='translation'?'translation':'rotation'}"; source="Door_${i+1}_source"; selection="door_${i+1}"; axis="door_${i+1}_axis"; memory=1; minValue=0; maxValue=1; ${d.motion==='translation'?`offset0=0; offset1=${(Math.hypot(...d.slide)*o.scale).toFixed(8)};`:`angle0=0; angle1=${(-d.angle*Math.PI/180).toFixed(8)};`} };`).join('\n')}
}; }; };\n`,
    mod:`name=${q(o.label)};
author=${q(o.author)};
tooltip=${q(o.label)};
actionName="";
action="";
description="Created with Arma 3 Better Tools by Calipo";
`};
}
